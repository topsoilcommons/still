#!/usr/bin/env python3
"""Build the pacer drift strip and its technical record on the Still page.

The strip is drawn from test/pacer_measurements.json, the committed record
of builder test runs. One mark per run, at the place its largest measured
drift falls on a band that runs from 0 to 20 milliseconds. Nothing here
is simulated: every mark is a run in that file. The strip does not move.
On this page only the breathing pacer moves, because the pacer is the
instrument itself.

The surface keeps the plain story only: the strip, a plain line beside it,
and the plain line of its printed key. The exact millisecond values, each
with its date, method, and source run, are generated into the closing
"For agents and builders" section, between the drift-tech markers. The
technical line of the key lives there too. Nothing is hand placed: change
the measurements file and rerun this tool.

Run: python3 tools/build_drift.py
"""

import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- drift:begin -->"
END = "<!-- drift:end -->"
TECH_BEGIN = "<!-- drift-tech:begin -->"
TECH_END = "<!-- drift-tech:end -->"
SCALE_MAX = 20


def fmt_date(value):
    parsed = date.fromisoformat(value)
    return parsed.strftime("%B %-d, %Y")


def main():
    data = json.loads(
        (ROOT / "test" / "pacer_measurements.json").read_text(
            encoding="utf-8"))
    runs = data["runs"]
    method = data["method"]
    marks = "\n".join(
        '    <span class="driftmark" style="left:%.1f%%" title="Run %d: largest drift %d %s"></span>'
        % (100.0 * r["max_drift_ms"] / SCALE_MAX, i + 1, r["max_drift_ms"],
           "millisecond" if r["max_drift_ms"] == 1 else "milliseconds")
        for i, r in enumerate(runs))
    section = """%s
<section aria-labelledby="drift-h">
  <h2 id="drift-h">Pacer timing, measured</h2>
  <p class="sub">The pacer keeps close to its marks. Its timing wanders by a hair from round to round, and every test run the builders recorded is shown on the strip below, just as it was measured. One run, taken while the machine was busy with other work, wandered more than the others, and it is shown too.</p>
  <div class="driftband" role="img" aria-label="A band with one mark for each recorded test run of the pacer. Most marks sit close to the start of the band, and one mark sits farther along.">
%s
  </div>
  <p class="sub">Key: one mark stands for one recorded test run of the pacer. A mark's place on the band shows how far that run's timing wandered from its marks. Most marks sit close together near the start of the band, and one sits farther along. The exact times for each run are listed in the builder record at the bottom of this page.</p>
</section>
%s""" % (BEGIN, marks, END)

    items = []
    for i, r in enumerate(runs):
        mean = ""
        if r.get("mean_drift_ms") is not None:
            mean = ", and its average drift was %s milliseconds" % (
                "%g" % r["mean_drift_ms"])
        unit = "millisecond" if r["max_drift_ms"] == 1 else "milliseconds"
        items.append(
            "    <li>Run %d: the largest drift was %d %s%s. "
            "Date: %s. Method: %s Source: %s</li>"
            % (i + 1, r["max_drift_ms"], unit, mean, fmt_date(r["date"]),
               method, r["source"]))
    tech = """%s
<h3>Pacer drift measurements</h3>
<p>Generated by tools/build_drift.py from test/pacer_measurements.json in this repository. Nothing in this list is typed by hand.</p>
<ul>
%s
</ul>
<p>Key, technical line: one mark per recorded run. A mark's place on the band is that run's largest drift from the ideal phase times. The band runs from 0 to %d milliseconds, and one unit is one millisecond. These are builder test runs on the build machine, labeled as such in the measurements file. This page collects nothing and makes no network calls.</p>
%s""" % (TECH_BEGIN, "\n".join(items), SCALE_MAX, TECH_END)

    path = ROOT / "index.html"
    page = path.read_text(encoding="utf-8")
    if BEGIN not in page or END not in page:
        print("build_drift: drift markers not found", file=sys.stderr)
        sys.exit(1)
    if TECH_BEGIN not in page or TECH_END not in page:
        print("build_drift: drift-tech markers not found", file=sys.stderr)
        sys.exit(1)
    before, rest = page.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    page = before + section + after
    before, rest = page.split(TECH_BEGIN, 1)
    _, after = rest.split(TECH_END, 1)
    page = before + tech + after
    path.write_text(page, encoding="utf-8")
    print("build_drift: %d runs drawn" % len(runs))


if __name__ == "__main__":
    main()
